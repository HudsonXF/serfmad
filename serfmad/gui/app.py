"""
serfmad.gui.app
===============
Tkinter + Matplotlib GUI viewer.

Tabs:
  1. Mission        -- single transit: fields, gradiometer, detection
  2. Field Budget   -- the ambient-nulling feasibility chain (the crux)
  3. Sensor Physics -- Bloch/Lindblad response, resonance, CAPE penalty
  4. Detection      -- Monte Carlo Pd vs range, ROC
  5. V&V            -- live verification & validation table

Design note: all plotting functions are pure (figure in, figure out) and live
in `serfmad.gui.plots`, so every figure in the report is generated by the SAME
code path the GUI displays. There is no separate "report plotting" script that
could drift from what the user sees.

RESPONSIVENESS
--------------
Every tab used to compute and render synchronously on the Tk main thread, so
the window was frozen for the whole render and Windows painted it "Not
Responding". Two things fix that, and neither touches the physics:

  1. Screen typesetting uses Matplotlib's mathtext, not real LaTeX. When a
     LaTeX install is present, `use_style()` auto-enables `text.usetex`, which
     shells out to latex.exe once per label; measured here that took the
     Surfaces tab from 1.9 s to 27.9 s and Detection from 6.7 s to 25.2 s.
     Report export (`plots.generate_all` / `hero.generate_all`) still
     auto-detects and still uses real LaTeX, so published figures are
     unchanged -- only the on-screen glyph renderer differs.
  2. Renders run on a single background worker thread that builds a DETACHED
     Figure (compute + artists, no Tk), which the main thread then installs
     and draws. Tk and the Tk canvas are only ever touched from the main
     thread, which is the only thread-safe way to do this.

The worker calls exactly the same plotting functions with exactly the same
arguments as before, so figure content and every number behind it are
unchanged; only *when* and *on which thread* the work happens is different.
"""

from __future__ import annotations
import sys
import queue
import threading
import time
import traceback
import numpy as np

import matplotlib
matplotlib.use("TkAgg")
from matplotlib.figure import Figure
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg, NavigationToolbar2Tk

import tkinter as tk
from tkinter import ttk

from ..constants import TARGETS, TARGET_LIBRARY, summary_table
from ..physics.platform import SEA_STATES
from ..mission import MissionConfig, run_mission, monte_carlo_detection
from ..backend import backend_report, describe as backend_describe
from ..validation.vv_suite import run_all, summary as vv_summary
from . import plots
from . import hero
from .style import use_style, latex_available


class SerfMadApp(tk.Tk):
    def __init__(self):
        super().__init__()
        # Apply the publication house style before any figure is created. The
        # screen deliberately uses mathtext even where a LaTeX install exists:
        # real usetex costs a latex.exe round trip per label, which froze the
        # UI for tens of seconds a tab. Report export re-detects and still
        # uses LaTeX, so published figures keep Computer Modern maths.
        self._usetex = use_style(usetex=False)
        self._latex_for_export = latex_available()
        tex = ("mathtext (screen) / LaTeX (export)" if self._latex_for_export
               else "mathtext")
        self.title(f"SERF-MAD Simulator  |  backend: {backend_report()}  "
                   f"|  typesetting: {tex}")
        self.geometry("1400x900")

        # --- render pipeline -------------------------------------------
        # One worker thread drains _req_q; finished figures come back on
        # _res_q, which the Tk main thread polls. A monotonic token per tab
        # means a superseded render is discarded rather than overwriting a
        # newer one when the user clicks through tabs quickly.
        self._req_q: queue.Queue = queue.Queue()
        self._res_q: queue.Queue = queue.Queue()
        self._token = 0
        self._latest: dict = {}
        self._inflight = 0
        self._last_install = 0.0
        self._worker = threading.Thread(target=self._worker_loop, daemon=True,
                                        name="serfmad-render")
        self._worker.start()

        self._build_controls()
        self._build_tabs()
        self.after(60, self._drain)
        self.after(200, self.run_mission_tab)

    # -- async render pipeline --------------------------------------------
    def _worker_loop(self):
        """Background renderer. Never touches Tk -- builds detached Figures."""
        while True:
            job = self._req_q.get()
            if job is None:
                return
            name, token, build = job
            if self._latest.get(name) != token:
                self._res_q.put((name, token, None, None, None))  # superseded
                continue
            try:
                fig = Figure(figsize=(12.6, 7.4), dpi=100)
                note = build(fig)
                self._res_q.put((name, token, fig, note, None))
            except BaseException:
                self._res_q.put((name, token, None, None, traceback.format_exc()))

    def _drain(self):
        """
        Main-thread poll: install finished figures, keep the UI alive.

        At most ONE figure is drawn per tick. Draining the whole queue in one
        callback stacked several draws into a single unbreakable block (4.0 s
        measured while clicking through tabs); one per tick caps the block at
        a single figure and lets Tk service events in between.
        """
        # The window can be closed with a render still in flight; touching a
        # destroyed widget then raises TclError out of the after() callback.
        try:
            if not self.winfo_exists():
                return
        except tk.TclError:
            return
        # One draw per tick is not enough on its own: a 3D surface takes ~1.2 s,
        # by which time the next tick is already due, so Tk can run several
        # _drain callbacks inside a single event-processing pass and chain the
        # draws into one long block (measured 7.9 s while spamming tabs).
        # Enforcing a floor on the gap between installs guarantees the event
        # loop is serviced between two draws. It only bites when results are
        # queued back-to-back; a lone render is unaffected.
        if time.perf_counter() - self._last_install < 0.15:
            self.after(30, self._drain)
            return
        try:
            while True:
                name, token, fig, note, err = self._res_q.get_nowait()
                self._inflight = max(0, self._inflight - 1)
                if self._latest.get(name) != token:
                    continue                      # stale result, drop it
                if err is not None:
                    self._set_status(f"{name}: ERROR (see console)")
                    print(err, file=sys.stderr)
                elif fig is not None:
                    self._install(name, fig)
                    self._set_status(note or f"{name} ready")
                break                             # one draw per tick
        except queue.Empty:
            pass
        if self._inflight == 0:
            self.run_btn.config(state=tk.NORMAL)
        self.after(30 if not self._res_q.empty() else 60, self._drain)

    def _install(self, name, fig):
        """
        Swap a finished Figure into its tab's existing canvas. Main thread only.

        The figure is sized to the widget BEFORE drawing, so the draw that
        follows is the only one: leaving the size mismatched makes the first
        expose event trigger a second full render, which on a 3D surface costs
        another ~3 s.
        """
        slot = self.tabs[name]
        canvas = slot["canvas"]
        old = canvas.figure

        widget = canvas.get_tk_widget()
        w, h = widget.winfo_width(), widget.winfo_height()
        if w > 1 and h > 1:
            fig.set_size_inches(w / fig.dpi, h / fig.dpi, forward=False)

        fig.set_canvas(canvas)
        canvas.figure = fig
        canvas.draw()

        slot["fig"] = fig
        self._last_install = time.perf_counter()
        if old is not None and old is not fig:
            old.clf()          # release the previous figure's artists

    def _submit(self, name, build, status):
        """Queue `build(fig)` for the worker thread."""
        self._token += 1
        self._latest[name] = self._token
        self._inflight += 1
        self.run_btn.config(state=tk.DISABLED)
        self._set_status(status)
        self._req_q.put((name, self._token, build))

    # -- controls ---------------------------------------------------------
    def _build_controls(self):
        bar = ttk.Frame(self, padding=6)
        bar.pack(side=tk.TOP, fill=tk.X)

        ttk.Label(bar, text="Target:").pack(side=tk.LEFT)
        self.target_var = tk.StringVar(value="Large UXO / naval mine")
        ttk.Combobox(bar, textvariable=self.target_var, width=34, state="readonly",
                     values=[t.label for t in TARGET_LIBRARY]).pack(side=tk.LEFT, padx=4)

        ttk.Label(bar, text="Sea state:").pack(side=tk.LEFT, padx=(12, 0))
        self.sea_var = tk.StringVar(value="moderate (SS3-4)")
        ttk.Combobox(bar, textvariable=self.sea_var, width=18, state="readonly",
                     values=list(SEA_STATES.keys())).pack(side=tk.LEFT, padx=4)

        ttk.Label(bar, text="Depth (m):").pack(side=tk.LEFT, padx=(12, 0))
        self.depth_var = tk.DoubleVar(value=12.0)
        ttk.Spinbox(bar, from_=2, to=200, increment=1, width=7,
                    textvariable=self.depth_var).pack(side=tk.LEFT, padx=4)

        ttk.Label(bar, text="Shield x:").pack(side=tk.LEFT, padx=(12, 0))
        self.shield_var = tk.DoubleVar(value=100.0)
        ttk.Spinbox(bar, from_=1, to=1000, increment=10, width=7,
                    textvariable=self.shield_var).pack(side=tk.LEFT, padx=4)

        ttk.Label(bar, text="Active null x:").pack(side=tk.LEFT, padx=(12, 0))
        self.null_var = tk.DoubleVar(value=100.0)
        ttk.Spinbox(bar, from_=1, to=5000, increment=10, width=7,
                    textvariable=self.null_var).pack(side=tk.LEFT, padx=4)

        ttk.Label(bar, text="Surface:").pack(side=tk.LEFT, padx=(12, 0))
        self.surface_var = tk.StringVar(value="hero_cape_surface")
        ttk.Combobox(bar, textvariable=self.surface_var, width=22,
                     state="readonly",
                     values=list(hero.HEROES.keys())).pack(side=tk.LEFT, padx=4)

        self.run_btn = ttk.Button(bar, text="Run", command=self.run_current_tab)
        self.run_btn.pack(side=tk.LEFT, padx=12)
        self.status = ttk.Label(bar, text="ready")
        self.status.pack(side=tk.LEFT, padx=8)

    def _build_tabs(self):
        self.nb = ttk.Notebook(self)
        self.nb.pack(fill=tk.BOTH, expand=True)
        self.tabs = {}
        for name in ["Mission", "Field Budget", "Sensor Physics",
                     "Detection", "Surfaces", "V&V"]:
            frame = ttk.Frame(self.nb)
            self.nb.add(frame, text=name)
            # Canvas and toolbar are created ONCE and never rebuilt. A render
            # swaps only the Figure into this canvas. Rebuilding the canvas
            # per render instead made Matplotlib draw each 3D surface several
            # times (measured: ~3x, 10.8 s of main-thread block) and churned
            # Tk Variable/Image objects that were then finalised on the worker
            # thread, raising "main thread is not in main loop".
            fig = Figure(figsize=(12.6, 7.4), dpi=100)
            canvas = FigureCanvasTkAgg(fig, master=frame)
            canvas.get_tk_widget().pack(fill=tk.BOTH, expand=True)
            toolbar = NavigationToolbar2Tk(canvas, frame)
            toolbar.update()
            self.tabs[name] = {"frame": frame, "fig": fig,
                               "canvas": canvas, "toolbar": toolbar}
        self.nb.bind("<<NotebookTabChanged>>", lambda e: self.run_current_tab())

    def _cfg(self) -> MissionConfig:
        return MissionConfig(
            target_label=self.target_var.get(),
            sea_state_label=self.sea_var.get(),
            target_depth_m=float(self.depth_var.get()),
            passive_shield=float(self.shield_var.get()),
            active_null=float(self.null_var.get()),
        )

    def _set_status(self, s):
        self.status.config(text=s)
        self.update_idletasks()

    # -- tab runners ------------------------------------------------------
    def run_current_tab(self):
        name = self.nb.tab(self.nb.select(), "text")
        {"Mission": self.run_mission_tab,
         "Field Budget": self.run_budget_tab,
         "Sensor Physics": self.run_physics_tab,
         "Detection": self.run_detection_tab,
         "Surfaces": self.run_surfaces_tab,
         "V&V": self.run_vv_tab}[name]()

    # Each runner reads its Tk control variables HERE, on the main thread,
    # then hands a closure over plain Python values to the worker. Reading a
    # tk.StringVar from the worker thread would be a Tk call off the main
    # thread -- exactly the thing that makes Tkinter crash unpredictably.

    def run_mission_tab(self):
        cfg = self._cfg()

        def build(fig):
            res = run_mission(cfg)
            plots.plot_mission(fig, res)
            return (f"detected={res.detection.detected}  "
                    f"SNR={res.snr_db:.1f} dB")
        self._submit("Mission", build, "running mission...")

    def run_budget_tab(self):
        cfg = self._cfg()

        def build(fig):
            plots.plot_field_budget(fig, cfg)
            return "field budget ready"
        self._submit("Field Budget", build, "computing field budget...")

    def run_physics_tab(self):
        def build(fig):
            plots.plot_sensor_physics(fig)
            return "sensor physics ready"
        self._submit("Sensor Physics", build, "solving sensor physics...")

    def run_detection_tab(self):
        target = self.target_var.get()

        def build(fig):
            plots.plot_detection(fig, target)
            return "Monte Carlo complete"
        self._submit("Detection", build,
                     "running Monte Carlo (this may take a moment)...")

    def run_surfaces_tab(self):
        """Matte-shaded 3D surfaces: quantities that live on a 2D plane."""
        which = self.surface_var.get()
        target = self.target_var.get()
        depth = float(self.depth_var.get())

        def build(fig):
            # 'interactive' decimates the plotted mesh ~3.7x for
            # responsiveness; measured worst-case pixel difference vs
            # 'publication' is <1%. Pass the toolbar state through so the
            # surfaces respond to the selected target and depth rather than
            # always showing defaults.
            hero.HEROES[which](fig, quality="interactive",
                               target=target, depth=depth)
            fig.subplots_adjust(left=-0.02, right=1.02, bottom=-0.05, top=1.0)
            return f"surface: {which}  |  target: {target}"
        self._submit("Surfaces", build, "rendering surfaces...")

    def run_vv_tab(self):
        def build(fig):
            results = run_all(verbose=False)
            s = vv_summary(results)
            plots.plot_vv_table(fig, results, s)
            return (f"V&V: {s['passed']}/{s['total']} passed, "
                    f"{s['failed']} failed, {s['skipped']} skipped")
        self._submit("V&V", build, "running V&V suite...")


def main():
    try:
        app = SerfMadApp()
        app.mainloop()
    except tk.TclError as exc:
        print("GUI could not start (no display available?).", file=sys.stderr)
        print(f"  {exc}", file=sys.stderr)
        print("\nRun headless figure generation instead:", file=sys.stderr)
        print("  python -m serfmad.gui.plots --outdir outputs", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
